def getDictLen(dict):
    length = 0
    for k in dict.keys():
        length += len(dict[k])
    return length


def bag_to_rgb_images(bag_file, image_topic, image_dir, start_time, end_time):
    """Extract a folder of RGB images from a rosbag."""
    print(
        "Extract images from %s on topic %s into %s"
        % (bag_file, image_topic, image_dir)
    )

    bag = rosbag.Bag(bag_file, "r")
    bridge = CvBridge()
    filename = 1
    for topic, msg, t in bag.read_messages(topics=[image_topic]):
        if start_time and end_time:
            if msg.header.stamp < start_time:
                continue
            if msg.header.stamp >= end_time:
                break
        cv_img = bridge.imgmsg_to_cv2(msg, desired_encoding="passthrough")
        cv2.imwrite(os.path.join(image_dir, "%04i.png" % filename), cv_img)
        filename += 1
        # im = Image.fromarray(depth_array)
        # if im.mode != 'RGB':
        #     im = im.convert('RGB')

        print("Wrote image %i" % filename)
    bag.close()
    return


def bag_to_depth_images(
    rosbag_name,
    depth_ros_topic,
    depth_dir,
    start_time,
    end_time,
    img_dir,
    bundletrack_depth_dir,
):
    """Extract a folder of depth images from a rosbag."""
    print(
        "Extract images from %s on topic %s into %s"
        % (rosbag_name, depth_ros_topic, depth_dir)
    )

    bag = rosbag.Bag(rosbag_name, "r")
    bridge = CvBridge()
