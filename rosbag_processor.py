def bag_to_pose(
    bagfile, pose_topic, outfile_position, outfile_velocity, start_frame, end_frame
):
    """
    Write /joint_states to a file
    """
    # To make sure we read images and poses approximately at the same rate
    offset = 32
    n = start_frame
    position = []
    velocity = []
    with rosbag.Bag(bagfile, "r") as bag:
        prev = start_frame
        for (topic, msg, ts) in bag.read_messages(topics=str(pose_topic)):
            if msg.header.seq < n:
                continue
            if msg.header.seq - prev <= offset:
                continue
            prev = msg.header.seq
            print("recording frame: ", msg.header.seq)
            reordered_position = [0] * len(msg.position)
            reordered_position[:7] = msg.position[2:]
            reordered_position[-2:] = msg.position[:2]
            reordered_velocity = [0] * len(msg.velocity)
            reordered_velocity[:7] = msg.velocity[2:]
            reordered_velocity[-2:] = msg.velocity[:2]

            position.append(reordered_position)
            velocity.append(reordered_velocity)
            n += 1
            if n == end_frame:
                break
        position = np.array(position)
        velocity = np.array(velocity)
        np.savetxt(outfile_position, position)
        np.savetxt(outfile_velocity, velocity)
        # check the shapes
        loaded_position = np.loadtxt(outfile_position)
        loaded_velocity = np.loadtxt(outfile_velocity)
        print("shape of position: ", position.shape)
        print("shape of loaded_position: ", loaded_position.shape)
        print("shape of velocity: ", velocity.shape)
        print("shape of loaded_velocity: ", loaded_velocity.shape)
    print(
        "wrote "
        + str(n)
        + " imu messages to the file: "
        + outfile_position
        + " and "
        + outfile_velocity
    )


def extract_poses_with_timestamps(
    bagfile,
    depth_topic,
    rgb_topic,
    pose_topic,
    outfile_position,
    outfile_rgb,
    start_time,
    end_time,
    bundletrack_rgb_dir,
):
    """
    Extract poses from rosbag according to matching timestamps between depth topic and pose topic.
    """
    bridge = CvBridge()
    depth_timestamps = {}  # depth topic
    pose_timestamps = {}  # pose topic
    final_pose_timestamps = {}  # timestamps to extract for pose topic
    rgb_timestamps = {}  # rgb topic
    final_rgb_timestamps = {}  # timestamps to extract for rgb topic
    position = []
    n = 0
    m = 0
    rgb_filename = 1
    with rosbag.Bag(bagfile, "r") as bag:
        for (topic, msg, ts) in bag.read_messages(topics=str(depth_topic)):
            print("processing ", ts)
            if msg.header.stamp.secs not in depth_timestamps.keys():
                depth_timestamps[msg.header.stamp.secs] = []
            depth_timestamps[msg.header.stamp.secs].append(msg.header.stamp.nsecs)
        print("The length of the depth_timestamps is {}".format(len(depth_timestamps)))

        # Processing pose topic
        # Get the hashmap for pose topic
        for (topic, msg, ts) in bag.read_messages(topics=str(pose_topic)):
            if msg.header.stamp.secs in depth_timestamps.keys():
                if msg.header.stamp.secs not in pose_timestamps.keys():
                    pose_timestamps[msg.header.stamp.secs] = []
                pose_timestamps[msg.header.stamp.secs].append(msg.header.stamp.nsecs)
        print("Finished processing pose_timestamps")

        for secs in tqdm(depth_timestamps.keys()):
            if secs not in final_pose_timestamps.keys():
                final_pose_timestamps[secs] = []
            for nsecs in depth_timestamps[secs]:
                closest_nsecs = math.inf
                result_nsecs = nsecs
                for pose_nsecs in pose_timestamps[secs]:
                    if abs(pose_nsecs - nsecs) < closest_nsecs:
                        result_nsecs = pose_nsecs
                        closest_nsecs = abs(pose_nsecs - nsecs)
                final_pose_timestamps[secs].append(result_nsecs)
        print("Finished recording final_pose_timestamps")

        # Extract poses with the timestamps we want to keep
        for (topic, msg, ts) in bag.read_messages(topics=str(pose_topic)):
            if (
                msg.header.stamp.secs in final_pose_timestamps.keys()
                and msg.header.stamp.nsecs
                in final_pose_timestamps[msg.header.stamp.secs]
            ):
                n += 1
                if start_time and end_time:
                    if msg.header.stamp < start_time:
                        continue
                    if msg.header.stamp >= end_time:
                        break
                reordered_position = [0] * len(msg.position)
                reordered_position[:7] = msg.position[2:]
                reordered_position[-2:] = msg.position[:2]
                position.append(reordered_position)

                print("Processing ", n, "th frame.")
        position = np.array(position)
        np.savetxt(outfile_position, position)
        # check the shapes
        loaded_position = np.loadtxt(outfile_position)
        print("shape of position: ", position.shape)
        print("shape of loaded_position: ", loaded_position.shape)

        # Processing RGB topic
        for (topic, msg, ts) in bag.read_messages(topics=str(rgb_topic)):
            if msg.header.stamp.secs in depth_timestamps.keys():
                if msg.header.stamp.secs not in rgb_timestamps.keys():
                    rgb_timestamps[msg.header.stamp.secs] = []
                rgb_timestamps[msg.header.stamp.secs].append(msg.header.stamp.nsecs)
        print("Finished processing rgb_timestamps")

        for secs in tqdm(depth_timestamps.keys()):
            if secs not in final_rgb_timestamps.keys():
                final_rgb_timestamps[secs] = []
            for nsecs in depth_timestamps[secs]:
                closest_nsecs = math.inf
                result_nsecs = nsecs
                for pose_nsecs in rgb_timestamps[secs]:
                    if abs(pose_nsecs - nsecs) < closest_nsecs:
                        result_nsecs = pose_nsecs
                        closest_nsecs = abs(pose_nsecs - nsecs)
                final_rgb_timestamps[secs].append(result_nsecs)
        print("Finished recording final_rgb_timestamps")

        for (topic, msg, ts) in bag.read_messages(topics=str(rgb_topic)):
            if (
                msg.header.stamp.secs in final_rgb_timestamps.keys()
                and msg.header.stamp.nsecs
                in final_rgb_timestamps[msg.header.stamp.secs]
            ):
                m += 1
                if start_time and end_time:
                    if msg.header.stamp < start_time:
                        continue
                    if msg.header.stamp >= end_time:
                        break
                cv_img = bridge.imgmsg_to_cv2(msg, desired_encoding="passthrough")
                cv2.imwrite(
                    os.path.join(outfile_rgb, "%04i.png" % rgb_filename), cv_img
                )
                cv2.imwrite(
                    os.path.join(bundletrack_rgb_dir, "%04i.png" % rgb_filename), cv_img
                )
                rgb_filename += 1
                print("Wrote image %i" % m)

    print("wrote " + str(n) + " imu messages to the file: " + outfile_position)


def extract_cube_pose(
    start_time,
    end_time,
    bagfile,
    odom_bagfile,
    odom_topic,
    odom_file_path,
    cam_translation,
    cam_axis_vec,
):
    """
    Extract the pose information of the cube for the start_frame from the rosbag generated by tagslam.
    """
    depth_bag = rosbag.Bag(bagfile, "r")
    odom_bag = rosbag.Bag(odom_bagfile, "r")
    secs = 0
    nsecs = 0
    depth_timestamps = {}
    odom_timestamps = {}
    final_odom_timestamps = {}
    print("Reading depth bag: %s and odom bag: %s" % (bagfile, odom_bagfile))
    for (topic, msg, ts) in depth_bag.read_messages(topics=str(DEPTH_ROS_TOPIC)):
        if start_time and end_time:
            if msg.header.stamp < start_time:
                continue
            if msg.header.stamp >= end_time:
                break
        if msg.header.stamp.secs not in depth_timestamps.keys():
            depth_timestamps[msg.header.stamp.secs] = []
        depth_timestamps[msg.header.stamp.secs].append(msg.header.stamp.nsecs)
    print("The length of the depth_timestamps is {}".format(len(depth_timestamps)))

    for (topic, msg, ts) in odom_bag.read_messages(topics=str(odom_topic)):
        if msg.header.stamp.secs in depth_timestamps.keys():
            if msg.header.stamp.secs not in odom_timestamps.keys():
                odom_timestamps[msg.header.stamp.secs] = []
            odom_timestamps[msg.header.stamp.secs].append(msg.header.stamp.nsecs)
    print("The length of odom_timestamps is {}".format(len(odom_timestamps)))
    for secs in tqdm(depth_timestamps.keys()):
        if secs not in final_odom_timestamps.keys():
            final_odom_timestamps[secs] = []
        for nsecs in depth_timestamps[secs]:
            closest_nsecs = math.inf
            result_nsecs = nsecs
            if secs not in odom_timestamps.keys():
                continue
            for pose_nsecs in odom_timestamps[secs]:
                if abs(pose_nsecs - nsecs) < closest_nsecs:
                    result_nsecs = pose_nsecs
                    closest_nsecs = abs(pose_nsecs - nsecs)
            final_odom_timestamps[secs].append(result_nsecs)
    frame_id = 0
    for topic, msg, t in odom_bag.read_messages(topics=str(odom_topic)):
        if (
            msg.header.stamp.secs in final_odom_timestamps.keys()
            and msg.header.stamp.nsecs in final_odom_timestamps[msg.header.stamp.secs]
        ):
            if start_time and end_time:
                if msg.header.stamp < start_time:
                    continue
                if msg.header.stamp >= end_time:
                    break
            print("Processing frame: ", frame_id)
            Q = np.zeros((4,))
            Q[0] = msg.pose.pose.orientation.x
            Q[1] = msg.pose.pose.orientation.y
            Q[2] = msg.pose.pose.orientation.z
            Q[3] = msg.pose.pose.orientation.w
            rotation_matrix = R.from_quat(Q).as_matrix()
            position = msg.pose.pose.position
            translation = np.array([[position.x], [position.y], [position.z]])
            result = np.vstack(
                (np.hstack((rotation_matrix, translation)), np.array([0, 0, 0, 1]))
            )
            result = world_to_camera(result, cam_translation, cam_axis_vec)
            np.savetxt(
                os.path.join(odom_file_path, "%04i.txt" % frame_id), result
            )  # save cube pose in camera frame
            print(
                "Saving the timestamp at: ",
                msg.header.stamp.secs,
                msg.header.stamp.nsecs,
            )
            break  # only need pose for the first frame
    depth_bag.close()
    odom_bag.close()
    return


