def find_nearest_neighbor(depth_timestamp):
    closest_diff = np.inf
    closest_nsecs = None
    closest_secs = None
    msg = None
    for i, odom_secs in enumerate(odom_timestamps_):
        for odom in odom_timestamps_[odom_secs]:
            if odom_secs == depth_timestamp.secs:
                diff = abs(depth_timestamp.nsecs - odom.rostime.nsecs)
                if diff < closest_diff:
                    closest_diff = diff
                    closest_nsecs = odom.rostime.nsecs
                    closest_secs = odom_secs
                    msg = odom.msg
    if closest_nsecs != None:
        my_list = odom_timestamps_[closest_secs]
        element_to_remove = BagInfo(
            rospy.rostime.Time(closest_secs, closest_nsecs), msg
        )
        odom_timestamps_[closest_secs] = [
            item for item in my_list if item != element_to_remove
        ]
        # print('Element removed!')
    return msg


def extract_time_versus_poses(
    start_time,
    end_time,
    depth_bag_file,
    odom_bag_file,
    depth_topic,
    odom_topic,
    output_dir,
    save=False,
    time_offset=0.0,
):
    depth_bag = rosbag.Bag(depth_bag_file, "r")
    odom_bag = rosbag.Bag(odom_bag_file, "r")
    bundletrack_time = []
    odom_time = []
    frame = 1
    tagslam_poses = []
    for (topic, msg, ts) in depth_bag.read_messages(topics=str(depth_topic)):
        if start_time and end_time:
            if msg.header.stamp < start_time:
                continue
            if msg.header.stamp >= end_time:
                break
        btime = msg.header.stamp.secs + msg.header.stamp.nsecs * 1e-9
        bundletrack_time.append(btime)
        frame+=1
    print("The length of the bundletrack_time is {}".format(len(bundletrack_time)))

    frame_id = 1
    for (topic, msg, ts) in odom_bag.read_messages(topics=str(odom_topic)):
        if start_time and end_time:
            if msg.header.stamp+rospy.Duration(time_offset) < start_time:
                continue
            if msg.header.stamp+rospy.Duration(time_offset) >= end_time:
                break
        shifted_timestamp = msg.header.stamp+rospy.Duration(time_offset)
        gtime = shifted_timestamp.secs + shifted_timestamp.nsecs * 1e-9
        odom_time.append(gtime)
        
        Q = np.zeros((7,))
        position = msg.pose.pose.position
        Q[0] = position.x
        Q[1] = position.y
        Q[2] = position.z
        Q[3] = msg.pose.pose.orientation.x
        Q[4] = msg.pose.pose.orientation.y
        Q[5] = msg.pose.pose.orientation.z
        Q[6] = msg.pose.pose.orientation.w
        tagslam_poses.append(Q)
        frame_id += 1
    tagslam_poses = np.array(tagslam_poses).T
    bundletrack_time = np.expand_dims(bundletrack_time,axis=0)
    odom_time = np.expand_dims(odom_time,axis=0)
    data = np.concatenate((odom_time, tagslam_poses), axis=0)
    data = data.T #N, 9
    if save:
        np.savetxt(output_dir + 'tagslam.txt', data)
        print(output_dir + 'tagslam.txt saved!')
    depth_bag.close()
    odom_bag.close()
    return bundletrack_time.reshape(-1,)


def extract_toss_duration(bagfile, topic, threshold):
    """
    Get start and end timestamps of tosses. New toss is defined as remainig static for longer than 3 seconds.

    :param threshold: rospy.Duration in second
    """
    bag = rosbag.Bag(bagfile, "r")
    prev_msg = None  # Pose of object in previous frame
    result_times = {}
    toss_idx = 1
    for (topic, msg, ts) in bag.read_messages(topics=str(topic)):

        def get_duration(msg1, msg2):
            # Assuming msg2 is after msg1
            diff = abs(msg2.header.stamp.to_nsec() - msg1.header.stamp.to_nsec())
            return diff

        def isclose(n1, n2, eps=0.01):
            return all(x <= eps for x in abs(n1 - n2))

        def is_static(msg1, msg2):
            P1, P2 = np.zeros((3,)), np.zeros((3,))
            P1[0] = msg1.pose.pose.position.x
            P1[1] = msg1.pose.pose.position.y
            P1[2] = msg1.pose.pose.position.z

            P2[0] = msg2.pose.pose.position.x
            P2[1] = msg2.pose.pose.position.y
            P2[2] = msg2.pose.pose.position.z
            # print(P1, P2)
            pos_static = isclose(P1, P2)
            Q1, Q2 = np.zeros((4,)), np.zeros((4,))
            Q1[0] = msg1.pose.pose.orientation.x
            Q1[1] = msg1.pose.pose.orientation.y
            Q1[2] = msg1.pose.pose.orientation.z
            Q1[3] = msg1.pose.pose.orientation.w

            Q2[0] = msg2.pose.pose.orientation.x
            Q2[1] = msg2.pose.pose.orientation.y
            Q2[2] = msg2.pose.pose.orientation.z
            Q2[3] = msg2.pose.pose.orientation.w
            # print(Q1, Q2)
            ori_static = isclose(Q1, Q2)
            return pos_static and ori_static

        if prev_msg != None and is_static(prev_msg, msg):
            # print(get_duration(prev_msg, msg))
            if get_duration(prev_msg, msg) >= threshold.to_nsec():
                prev_msg = msg
                if toss_idx not in result_times:
                    result_times[toss_idx] = []
                result_times[toss_idx].append(prev_msg.header.stamp)
                result_times[toss_idx].append(msg.header.stamp)
                toss_idx += 1
        else:
            prev_msg = msg

    bag.close()
    print(result_times)
    return result_times

def extract_timestamps(bagfile, topic, start_time, end_time):
    """
    Extract timestamps from rosbag in specified range.
    """
    timestamps = []
    bag = rosbag.Bag(bagfile, "r")
    for (topic, msg, ts) in bag.read_messages(topics=str(topic)):
        if start_time <= msg.header.stamp < end_time:
            timestamps.append(msg.header.stamp)
    return timestamps

